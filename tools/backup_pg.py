"""
Backup PostgreSQL Schema to SQL file using psycopg
"""
import argparse
import sys
import psycopg

def dump_schema(dsn: str, schema: str, output_path: str):
    print(f"Connecting to database to dump schema '{schema}'...")
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT table_name 
                FROM information_schema.tables 
                WHERE table_schema = %s AND table_type = 'BASE TABLE'
                ORDER BY table_name;
            """, (schema,))
            tables = [r[0] for r in cur.fetchall()]
            print(f"Found {len(tables)} tables in schema '{schema}'.")

            with open(output_path, "w", encoding="utf-8") as f:
                f.write(f"-- PostgreSQL Backup for Schema: {schema}\n")
                f.write(f"-- Generated by tools/backup_pg.py\n\n")
                f.write(f"CREATE SCHEMA IF NOT EXISTS {schema};\n")
                f.write(f"SET search_path TO {schema}, public;\n\n")

                for tbl in tables:
                    print(f"  Dumping table {tbl}...", end=" ", flush=True)
                    cur.execute(f"SELECT COUNT(*) FROM {schema}.{tbl};")
                    count = cur.fetchone()[0]
                    f.write(f"-- Table: {schema}.{tbl} ({count} rows)\n")
                    
                    # Fetch columns
                    cur.execute(f"""
                        SELECT column_name, data_type 
                        FROM information_schema.columns 
                        WHERE table_schema = %s AND table_name = %s
                        ORDER BY ordinal_position;
                    """, (schema, tbl))
                    cols = [r[0] for r in cur.fetchall()]
                    cols_str = ", ".join(cols)

                    cur.execute(f"SELECT {cols_str} FROM {schema}.{tbl};")
                    rows = cur.fetchall()
                    if rows:
                        for row in rows:
                            vals = []
                            for v in row:
                                if v is None:
                                    vals.append("NULL")
                                elif isinstance(v, (int, float)):
                                    vals.append(str(v))
                                elif isinstance(v, bool):
                                    vals.append("TRUE" if v else "FALSE")
                                else:
                                    escaped = str(v).replace("'", "''")
                                    vals.append(f"'{escaped}'")
                            f.write(f"INSERT INTO {schema}.{tbl} ({cols_str}) VALUES ({', '.join(vals)}) ON CONFLICT DO NOTHING;\n")
                    f.write("\n")
                    print(f"Done ({count} rows)")

    print(f"\nBackup successfully saved to: {output_path}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", required=True)
    parser.add_argument("--schema", default="wms")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    dump_schema(args.url, args.schema, args.output)
